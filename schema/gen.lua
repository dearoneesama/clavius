-- Writes the node modules from schema/. Run from the project root.

--- One field of a node type: { name, type, doc }.
--- @alias NodeField string[]

--- One node type in schema/source.lua or schema/core.lua.
--- @class NodeType
--- @field tag string
--- @field doc string|nil
--- @field fields NodeField[]

--- A schema file and the node module generated from it.
--- @class Schema
--- @field path string schema file, relative to the project root
--- @field prefix string class-name prefix, e.g. 'Src'
--- @field module string generated node module, relative to the project root
--- @field family string|nil M.<family> for sexpr

--- @type Schema[]
local SCHEMAS = {
    { path = 'schema/source.lua', prefix = 'Src', module = 'src/clavius/ir/source_nodes.lua', family = 'source' },
    { path = 'schema/core.lua', prefix = 'Core', module = 'src/clavius/ir/core_nodes.lua', family = 'core' },
}

local SEXPR_SCHEMA = 'src/clavius/sexpr/schema.lua'

--- Returns the LuaLS type of a field in the generated class.
--- @param ty string
--- @return string
local function lua_type(ty)
    if ty == 'node' then
        return 'NodeId'
    elseif ty == 'node?' then
        return 'NodeId|nil'
    elseif ty == 'node[]' then
        return 'NodeId[]'
    elseif ty == 'string?' then
        return 'string|nil'
    end
    return ty
end

--- Returns whether a field of type `ty` holds child nodes.
--- @param ty string
--- @return boolean
local function is_child_type(ty)
    return ty == 'node' or ty == 'node?' or ty == 'node[]'
end

--- Returns whether nodes of this type have children.
--- @param node_type NodeType
--- @return boolean
local function has_children(node_type)
    for _, f in ipairs(node_type.fields) do
        if is_child_type(f[2]) then
            return true
        end
    end
    return false
end

--- Generates the node module for one schema: classes, the tag and node unions, and `children`.
--- @param schema Schema
--- @param node_types NodeType[]
--- @return string
local function node_module(schema, node_types)
    local out = { ('-- Generated by schema/gen.lua from %s. Do not edit.'):format(schema.path), '' }
    --- @param s string
    local function emit(s)
        out[#out + 1] = s
    end
    for _, t in ipairs(node_types) do
        if t.doc then
            emit(('--- %s'):format(t.doc))
        end
        emit(('--- @class %s%s'):format(schema.prefix, t.tag))
        emit(("--- @field tag '%s'"):format(t.tag))
        for _, f in ipairs(t.fields) do
            local line = ('--- @field %s %s'):format(f[1], lua_type(f[2]))
            if f[3] then
                line = ('%s %s'):format(line, f[3])
            end
            emit(line)
        end
        emit ''
    end
    emit(('--- @alias %sTag'):format(schema.prefix))
    for _, t in ipairs(node_types) do
        emit(("--- | '%s'"):format(t.tag))
    end
    emit ''
    emit(('--- @alias %sNode'):format(schema.prefix))
    for _, t in ipairs(node_types) do
        emit(('--- | %s%s'):format(schema.prefix, t.tag))
    end
    emit ''
    emit 'local M = {}'
    emit ''
    emit "--- Returns the ids of a node's children, in evaluation order."
    emit(('--- @param n %sNode'):format(schema.prefix))
    emit '--- @return NodeId[] kids'
    emit 'function M.children(n)'
    emit '    local kids = {}'
    local first = true
    for _, t in ipairs(node_types) do
        if has_children(t) then
            emit(("    %s n.tag == '%s' then"):format(first and 'if' or 'elseif', t.tag))
            first = false
            for _, f in ipairs(t.fields) do
                local name, ty = f[1], f[2]
                if ty == 'node' then
                    emit(('        kids[#kids + 1] = n.%s'):format(name))
                elseif ty == 'node?' then
                    emit(('        if n.%s ~= nil then'):format(name))
                    emit(('            kids[#kids + 1] = n.%s'):format(name))
                    emit '        end'
                elseif ty == 'node[]' then
                    emit(('        for _, kid in ipairs(n.%s) do'):format(name))
                    emit '            kids[#kids + 1] = kid'
                    emit '        end'
                end
            end
        end
    end
    if not first then
        emit '    end'
    end
    emit '    return kids'
    emit 'end'
    emit ''
    emit 'return M'
    return table.concat(out, '\n') .. '\n'
end

--- Returns the s-expression shape of a field type and the allowed symbols of an enum.
--- @param ty string
--- @return string shape
--- @return string[]|nil values
local function sexpr_shape(ty)
    local shapes = {
        node = 'node',
        ['node?'] = 'opt',
        ['node[]'] = 'list',
        integer = 'int',
        boolean = 'bool',
        string = 'str',
        ['string?'] = 'opt_str',
    }
    if shapes[ty] then
        return shapes[ty], nil
    end
    -- a union of string literals, e.g. "'int' | 'bool'"
    local values = {}
    for v in ty:gmatch "'([^']*)'" do
        values[#values + 1] = v
    end
    assert(#values > 0, ('gen: unknown field type %s'):format(ty))
    return 'enum', values
end

--- Generates the s-expression schema: each kind's fields in order with their shapes.
--- @param families Schema[]
--- @param node_types NodeType[][] the node types of each schema in `families`
--- @return string
local function sexpr_module(families, node_types)
    local paths = {}
    for i, schema in ipairs(families) do
        paths[i] = schema.path
    end
    local out = {
        ('-- Generated by schema/gen.lua from %s. Do not edit.'):format(table.concat(paths, ', ')),
        '',
        '--- How one field of a node is written in an s-expression.',
        '--- @class SexpFieldSpec',
        '--- @field name string',
        "--- @field shape 'node' | 'opt' | 'list' | 'int' | 'bool' | 'str' | 'opt_str' | 'enum'",
        '--- @field values string[]|nil the symbols an `enum` field allows',
        '',
        'local M = {}',
    }
    --- @param s string
    local function emit(s)
        out[#out + 1] = s
    end
    for i, schema in ipairs(families) do
        emit ''
        emit '--- @type table<string, SexpFieldSpec[]>'
        emit(('M.%s = {'):format(schema.family))
        for _, t in ipairs(node_types[i]) do
            if #t.fields == 0 then
                emit(('    %s = {},'):format(t.tag))
            else
                emit(('    %s = {'):format(t.tag))
            end
            for _, f in ipairs(t.fields) do
                local shape, values = sexpr_shape(f[2])
                if values then
                    local quoted = {}
                    for j, v in ipairs(values) do
                        quoted[j] = ("'%s'"):format(v)
                    end
                    local list = table.concat(quoted, ', ')
                    local line = ("        { name = '%s', shape = '%s', values = { %s } },"):format(f[1], shape, list)
                    -- too wide for one line, so each field gets its own line like stylua writes it
                    if #line > 150 then
                        emit '        {'
                        emit(("            name = '%s',"):format(f[1]))
                        emit(("            shape = '%s',"):format(shape))
                        emit(('            values = { %s },'):format(list))
                        emit '        },'
                    else
                        emit(line)
                    end
                else
                    emit(("        { name = '%s', shape = '%s' },"):format(f[1], shape))
                end
            end
            if #t.fields > 0 then
                emit '    },'
            end
        end
        emit '}'
    end
    emit ''
    emit 'return M'
    return table.concat(out, '\n') .. '\n'
end

--- @param path string
--- @param text string
local function write_file(path, text)
    local f = assert(io.open(path, 'wb'))
    f:write(text)
    f:close()
end

local families, family_types = {}, {}
for _, schema in ipairs(SCHEMAS) do
    --- @type NodeType[]
    local node_types = assert(loadfile(schema.path))()
    write_file(schema.module, node_module(schema, node_types))

    if schema.family then
        families[#families + 1] = schema
        family_types[#family_types + 1] = node_types
    end
end

write_file(SEXPR_SCHEMA, sexpr_module(families, family_types))
